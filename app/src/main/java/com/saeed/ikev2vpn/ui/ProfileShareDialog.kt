import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext

private class GeneratedProfileShare(val link: String, val qr: Bitmap) {
    override fun toString() = "GeneratedProfileShare(<redacted>)"
}

@Composable
internal fun ProfileShareDialog(
    profile: StoredProfile,
    createLink: suspend (String, Boolean) -> String,
    onDismiss: () -> Unit,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var includePassword by remember(profile.config.id) { mutableStateOf(false) }
    // Reset immediately when the password option changes so stale QR/link actions cannot be used.
    var generated by remember(profile.config.id, includePassword) { mutableStateOf<GeneratedProfileShare?>(null) }
    var error by remember(profile.config.id, includePassword) { mutableStateOf<String?>(null) }
    var actionMessage by remember(profile.config.id, includePassword) { mutableStateOf<String?>(null) }
    var sharing by remember { mutableStateOf(false) }
    LaunchedEffect(profile.config.id, includePassword) {
        try {
            val link = createLink(profile.config.id, includePassword)
            generated = withContext(Dispatchers.Default) {
                val matrix = QrCodeEncoder.encode(link)
                val pixels = IntArray(matrix.width * matrix.height) { index ->
                    if (matrix[index % matrix.width, index / matrix.width]) android.graphics.Color.BLACK
                    else android.graphics.Color.WHITE
                }
                GeneratedProfileShare(link, Bitmap.createBitmap(pixels, matrix.width, matrix.height, Bitmap.Config.ARGB_8888))
            }
        } catch (exception: CancellationException) {
            throw exception
        } catch (exception: IkevProfileShareException) {
            error = exception.message
        } catch (_: Exception) {
            error = "This configuration could not be shared. Try again or share without a password."
        }
    }
    AlertDialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(securePolicy = SecureFlagPolicy.SecureOn),
        title = { Text("Share ${profile.config.profileName}") },
        text = {
            Column(Modifier.verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Text("Scan this QR in IKEv2 VPN or import the configuration link.")
                Row(Modifier.fillMaxWidth().toggleable(value = includePassword, enabled = !sharing,
                    role = Role.Checkbox, onValueChange = { includePassword = it }),
                    verticalAlignment = Alignment.CenterVertically) {
                    Checkbox(checked = includePassword, onCheckedChange = null)
                    Spacer(Modifier.width(8.dp))
                    Text("Include saved password")
                }
                Text(if (includePassword) "Anyone with this link or QR can read and use your VPN password. Share only with someone you trust."
                    else "The recipient will need to enter the VPN password.", style = MaterialTheme.typography.bodySmall)
                if (profile.config.appRouting.mode != com.saeed.ikev2vpn.data.AppRoutingMode.ALL) {
                    Text("App routing stays on this device. Imported connections start with All apps.",
                        style = MaterialTheme.typography.bodySmall)
                }
                error?.let { Text(it, color = MaterialTheme.colorScheme.error) }
                val share = generated
                if (share == null && error == null) {
                    CircularProgressIndicator(Modifier.align(Alignment.CenterHorizontally))
                }
                if (share != null) {
                    Image(share.qr.asImageBitmap(), contentDescription = "Configuration QR for ${profile.config.profileName}",
                        modifier = Modifier.fillMaxWidth().aspectRatio(1f), filterQuality = FilterQuality.None)
                    OutlinedButton(enabled = !sharing, modifier = Modifier.fillMaxWidth(), onClick = {
                        try {
                            val clip = ClipData.newPlainText("VPN configuration link", share.link)
                            if (includePassword) clip.description.extras = PersistableBundle().apply {
                                putBoolean("android.content.extra.IS_SENSITIVE", true)
                            }
                            (context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager).setPrimaryClip(clip)
                            actionMessage = "Link copied"
                        } catch (_: Exception) { actionMessage = "The link could not be copied." }
                    }) { Text("Copy link") }
                    OutlinedButton(enabled = !sharing, modifier = Modifier.fillMaxWidth(), onClick = {
                        try {
                            context.startActivity(Intent.createChooser(ProfileShareIntents.link(share.link), "Share configuration link"))
                        } catch (_: Exception) { actionMessage = "No app is available to share this link." }
                    }) { Text("Share link") }
                    OutlinedButton(enabled = !sharing, modifier = Modifier.fillMaxWidth(), onClick = {
                        sharing = true
                        scope.launch {
                            try {
                                val intent = withContext(Dispatchers.IO) { ProfileShareIntents.qr(context, share.qr) }
                                context.startActivity(Intent.createChooser(intent, "Share configuration QR"))
                            } catch (exception: CancellationException) {
                                throw exception
                            } catch (_: Exception) { actionMessage = "The QR image could not be shared. Try sharing the link." }
                            finally { sharing = false }
                        }
                    }) { Text(if (sharing) "Preparing image…" else "Share QR image") }
                }
                actionMessage?.let { Text(it, style = MaterialTheme.typography.bodySmall) }
            }
        },
        confirmButton = { TextButton(onClick = onDismiss) { Text("Close") } },
    )
}
